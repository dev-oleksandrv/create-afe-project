#!/usr/bin/env bash
# Prints the decision index from the front matter of the records.
# Usage: scripts/gen-decisions-index.sh > docs/decisions/README.md
# scripts/check-decisions.sh fails when the committed index differs from this output.
set -euo pipefail
cd "$(dirname "$0")/.."

# Prints front-matter field $1 of the record read from stdin, without surrounding quotes.
field() {
  tr -d '\r' | awk -v k="$1" 'NR==1 && $0!="---" {exit} NR>1 && $0=="---" {exit}
       NR>1 && index($0, k ":")==1 {
         v = substr($0, length(k) + 2); sub(/^[[:space:]]+/, "", v); sub(/[[:space:]]+$/, "", v)
         if (v ~ /^".*"$/) v = substr(v, 2, length(v) - 2)
         print v; exit}'
}

# Prints the first level-one heading after the front matter.
title() {
  awk 'NR==1 && $0=="---" {fm=1; next} fm && $0=="---" {fm=0; next}
       !fm && /^# / {sub(/^# /, ""); print; exit}'
}

# Prints $1 as a table cell: "–" when empty, pipes escaped.
cell() {
  local v="${1:-}"
  [ -n "$v" ] || v="–"
  printf '%s' "${v//|/\\|}"
}

shopt -s nullglob
records=(docs/decisions/[0-9][0-9][0-9][0-9]-*.md)

cat <<'EOF'
# Decision records

Generated by `scripts/gen-decisions-index.sh` from the front matter of the records; do not edit
by hand. Read this index first and open a record only when the task needs it. Which decisions get
a record, and how to write one: [`adr-template.md`](adr-template.md).

EOF
if [ "${#records[@]}" -eq 0 ]; then
  echo "No records yet."
  exit 0
fi
cat <<'EOF'
| ADR | Status | Scope | Decision | Summary | Supersedes |
| --- | --- | --- | --- | --- | --- |
EOF
for f in "${records[@]}"; do
  name=$(basename "$f")
  printf '| [%s](%s) | %s | %s | %s | %s | %s |\n' "${name:0:4}" "$name" \
    "$(cell "$(field status < "$f")")" "$(cell "$(field scope < "$f")")" \
    "$(cell "$(title < "$f")")" "$(cell "$(field summary < "$f")")" \
    "$(cell "$(field supersedes < "$f" | tr -d '[]')")"
done
